"""Optional local OCR and source-page rendering. No cloud OCR service."""
import csv
import io
import os
import shutil
import subprocess
from pathlib import Path
from src.config import DATA_DIR

ORIGINALS_DIR = DATA_DIR / 'originals'
ORIGINALS_DIR.mkdir(parents=True, exist_ok=True)


def ocr_page(page):
    executable = shutil.which('tesseract')
    if not executable:
        return '', [], 'Scanned pages need Tesseract installed locally to enable OCR.'
    import fitz
    pixmap = page.get_pixmap(matrix=fitz.Matrix(2, 2))
    result = subprocess.run([executable, 'stdin', 'stdout', '-l', os.environ.get('OCR_LANGUAGES', 'eng'), '--psm', '3', 'tsv'],
                            input=pixmap.tobytes('png'), capture_output=True, timeout=60, check=True)
    words, lines, last_line = [], [], None
    for word in csv.DictReader(io.StringIO(result.stdout.decode('utf-8')), delimiter='\t'):
        if not word.get('text', '').strip() or float(word.get('conf', '-1')) < 0:
            continue
        line = (word['block_num'], word['par_num'], word['line_num'])
        if line != last_line:
            lines.append([])
            last_line = line
        lines[-1].append(word['text'])
        x, y, w, h = [float(word[k]) / 2 for k in ['left', 'top', 'width', 'height']]
        words.append({'text': word['text'], 'rect': [x, y, x + w, y + h]})
    return '\n'.join(' '.join(line) for line in lines), words, None


def retain_original(document_id, file_type, source):
    # The document id is generated by the backend, never a user filename.
    destination = ORIGINALS_DIR / f'{document_id}.{file_type}'
    if not destination.exists():
        temporary = destination.with_suffix(destination.suffix + '.tmp')
        shutil.copyfile(source, temporary)
        temporary.replace(destination)


def original_path(document):
    return ORIGINALS_DIR / f"{document['id']}.{document['file_type']}"


def render_page(path, page_number, excerpt='', ocr_words=None):
    import fitz
    import re
    with fitz.open(path) as doc:
        if not 1 <= page_number <= len(doc):
            raise ValueError('Page number is outside this PDF')
        page = doc[page_number - 1]
        rectangles = []
        if excerpt.strip():
            rectangles = page.search_for(excerpt[:350]) or page.search_for(excerpt[:100])
            if not rectangles and ocr_words:
                normalize = lambda s: re.sub(r'\W+', '', s.casefold())
                target = normalize(excerpt[:160])
                for start in range(len(ocr_words)):
                    combined = ''
                    for end in range(start, min(start + 50, len(ocr_words))):
                        combined += normalize(ocr_words[end]['text'])
                        if combined and target.startswith(combined):
                            if len(combined) >= len(target) * .8:
                                rectangles = [fitz.Rect(w['rect']) for w in ocr_words[start:end + 1]]
                                break
                        else:
                            break
                    if rectangles:
                        break
            for rect in rectangles:
                page.add_highlight_annot(rect)
        return page.get_pixmap(matrix=fitz.Matrix(1.5, 1.5), annots=True).tobytes('png'), len(doc), bool(rectangles)
